function isEnglish() {
  try { return wx.getStorageSync('lang') === 'en'; } catch (e) { return false; }
}

function translate(text) {
  if (!isEnglish()) return text;
  if (typeof text !== 'string' || !text) return text;
  const key = text.trim();
  if (!key) return text;
  if (EXACT[key]) return EXACT[key];
  for (let i = 0; i < RULES.length; i++) {
    if (RULES[i][0].test(key)) return key.replace(RULES[i][0], RULES[i][1]);
  }
  return text;
}

function localizeOptions(options, kind) {
  if (!options || typeof options !== 'object') return options;
  const out = Object.assign({}, options);
  ['title', 'content', 'confirmText', 'cancelText', 'placeholderText'].forEach(k => {
    if (typeof out[k] === 'string') out[k] = translate(out[k]);
  });
  if (kind === 'actionSheet' && Array.isArray(out.itemList)) {
    out.itemList = out.itemList.map(item => translate(item));
  }
  return out;
}

let installed = false;
function install() {
  if (installed || typeof wx === 'undefined') return;
  installed = true;
  const names = ['showToast', 'showModal', 'showLoading', 'showActionSheet'];
  names.forEach(name => {
    const original = wx[name];
    if (typeof original !== 'function') return;
    const kind = name === 'showActionSheet' ? 'actionSheet' : name;
    wx[name] = function (options) {
      if (!isEnglish()) return original.call(wx, options);
      return original.call(wx, localizeOptions(options, kind));
    };
  });
}

